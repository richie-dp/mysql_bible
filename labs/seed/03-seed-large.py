#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""shop 库订单造数器：只用标准库，输出可直接喂给 mysql 客户端的 INSERT 流。

用法：
    python3 03-seed-large.py --rows 10000000 > big.sql
    python3 03-seed-large.py --rows 2000000 --skew > skew.sql
    mysql -h127.0.0.1 -P3306 -uroot -p shop < big.sql

约定：
    1. 先跑 01-schema.sql；导入前 TRUNCATE order_main、order_item。
    2. id 由脚本显式给出（1..rows），这样 order_item 能直接引用，不用回查自增值。
    3. 每 1000 行一条 INSERT；pay_amount 严格等于明细金额之和，对账不会差一分。
    4. --skew 让 10% 的订单压到同一个爆款 SKU（8842）和同一个热点商户（1000），
       均匀分布造不出锁冲突，也造不出执行计划的偏差。
"""
import argparse
import random
import sys
from datetime import datetime, timedelta

SKU_BASE = 8800
SKU_COUNT = 2000
HOT_SKU = 8842
MERCHANT_BASE = 1000
MERCHANT_COUNT = 500
HOT_MERCHANT = 1000
STATUSES = (10, 20, 30, 90, 99)
STATUS_WEIGHTS = (5, 10, 30, 50, 5)

ORDER_COLS = ("id, order_no, merchant_id, buyer_id, status, "
              "pay_amount, created_at, paid_at")
ITEM_COLS = "order_id, line_no, sku_id, sku_name, unit_price, qty"


def money(cents):
    """整数分 -> DECIMAL(18,2) 字面量，避免浮点误差"""
    return "%d.%02d" % (cents // 100, cents % 100)


def stamp(d):
    """datetime -> 'YYYY-MM-DD HH:MM:SS.mmm'（DATETIME(3) 的字面量）"""
    return d.strftime("%Y-%m-%d %H:%M:%S.") + "%03d" % (d.microsecond // 1000)


def emit(out, table, cols, rows):
    out.write("INSERT INTO %s (%s) VALUES\n" % (table, cols))
    out.write(",\n".join(rows))
    out.write(";\n")


def price_cents(sku):
    """同一个 SKU 的价格固定：让范围查询的选择性可复现"""
    return 990 + (sku * 37) % 90000


def build(args):
    rng = random.Random(args.seed)
    base = datetime(args.start_year, args.start_month, 1)
    span = args.days * 86400

    out = sys.stdout
    out.write("-- generated by 03-seed-large.py --rows %d%s\n"
              % (args.rows, " --skew" if args.skew else ""))
    out.write("-- 目标表：shop.order_main / shop.order_item（导入前 TRUNCATE）\n")
    out.write("SET NAMES utf8mb4;\nUSE shop;\n")

    order_rows, item_rows = [], []
    for i in range(1, args.rows + 1):
        created = base + timedelta(seconds=rng.randrange(span),
                                   milliseconds=rng.randrange(1000))
        status = rng.choices(STATUSES, STATUS_WEIGHTS)[0]
        hot = args.skew and i % 10 == 0
        merchant = HOT_MERCHANT if hot else MERCHANT_BASE + rng.randrange(MERCHANT_COUNT)
        buyer = 100000 + rng.randrange(50000)

        total = 0
        lines = []
        for line_no in range(1, 2 + (i - 1) % 3):
            if hot and line_no == 1:
                sku = HOT_SKU
            else:
                sku = SKU_BASE + rng.randrange(SKU_COUNT)
            qty = 1 + rng.randrange(3)
            unit = price_cents(sku)
            total += unit * qty
            lines.append("(%d,%d,%d,'SKU-%d',%s,%d)"
                         % (i, line_no, sku, sku, money(unit), qty))

        paid = "NULL" if status == 10 else "'%s'" % stamp(
            created + timedelta(minutes=1 + rng.randrange(30)))
        order_rows.append("(%d,'SO%s%012d',%d,%d,%d,%s,'%s',%s)"
                          % (i, created.strftime("%Y%m%d"), i, merchant, buyer,
                             status, money(total), stamp(created), paid))
        item_rows.extend(lines)

        if len(order_rows) >= args.batch:
            emit(out, "order_main", ORDER_COLS, order_rows)
            order_rows = []
        if len(item_rows) >= args.batch:
            emit(out, "order_item", ITEM_COLS, item_rows)
            item_rows = []

    if order_rows:
        emit(out, "order_main", ORDER_COLS, order_rows)
    if item_rows:
        emit(out, "order_item", ITEM_COLS, item_rows)
    out.write("-- 导入完成后执行：ANALYZE TABLE order_main, order_item;\n")
    print("done: %d orders, --skew=%s, seed=%d"
          % (args.rows, args.skew, args.seed), file=sys.stderr)


def main():
    p = argparse.ArgumentParser(description="生成 shop 订单测试数据（SQL 流）")
    p.add_argument("--rows", type=int, default=1000000,
                   help="订单行数，默认 100 万")
    p.add_argument("--skew", action="store_true",
                   help="10%% 的订单集中到 SKU 8842 与商户 1000")
    p.add_argument("--batch", type=int, default=1000,
                   help="每条 INSERT 的行数，默认 1000")
    p.add_argument("--seed", type=int, default=20261114, help="随机种子")
    p.add_argument("--days", type=int, default=40, help="created_at 铺开的天数")
    p.add_argument("--start-year", type=int, default=2026)
    p.add_argument("--start-month", type=int, default=9)
    args = p.parse_args()
    if args.rows < 1:
        p.error("--rows 必须 >= 1")
    if args.batch < 1:
        p.error("--batch 必须 >= 1")
    build(args)


if __name__ == "__main__":
    main()
